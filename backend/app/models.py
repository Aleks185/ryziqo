ModuleIds = list[Literal[1, 2, 3]]


class ReportInput(BaseModel):
    source_channel: Literal["api", "analyst_panel", "public_form"] = "api"
    platform: Literal["Meta / Facebook", "Google Ads", "YouTube", "TikTok", "X", "Strona WWW", "Komunikator / SMS", "Inne"] | None = None
    force_full: bool = False
    # Citizen consent: "none" = verdict only (nothing stored), "anonymous" = stored without reporter
    # identifiers, "signed" = stored with a pseudonym; null keeps the default behaviour of the API
    share_mode: Literal["none", "anonymous", "signed"] | None = None
    reporter_display_name: str | None = Field(default=None, max_length=40)
    # Random per-browser key: groups a pseudonym's reports without accounts (stored only as HMAC)
    reporter_key: str | None = Field(default=None, min_length=16, max_length=64, pattern=r"^[A-Za-z0-9-]+$")

    @model_validator(mode="after")
    def _signed_needs_identity(self) -> "ReportInput":
        if self.reporter_display_name is not None:
            self.reporter_display_name = " ".join(self.reporter_display_name.split()) or None
        if self.share_mode == "signed" and not (self.reporter_display_name and self.reporter_key):
            raise ValueError("Zgłoszenie podpisane wymaga pseudonimu i klucza zgłaszającego.")
        if self.share_mode != "signed":
            self.reporter_display_name = None
            self.reporter_key = None
        return self

    @property
    def persist(self) -> bool:
        return self.share_mode != "none"


