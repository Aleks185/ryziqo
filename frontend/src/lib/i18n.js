export const translate = (lang, key) => DICT[lang]?.[key] ?? DICT.pl[key] ?? key;

// source_platform z CONTRACT.md; nieznane wartości pokazujemy dosłownie.
export const platformLabel = (t, platform) => {
  const key = `src_${platform}`;
  const label = t(key);
  return label === key ? platform || "—" : label;
};

export const formatDate = (iso, lang) =>
  iso
    ? new Intl.DateTimeFormat(lang === "pl" ? "pl-PL" : "en-GB", { dateStyle: "short", timeStyle: "medium" }).format(new Date(iso))
    : "—";
